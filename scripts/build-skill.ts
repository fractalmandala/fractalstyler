function renderTokenIndex(facts: Facts): string {
	const md: string[] = [
		'# Token Reference',
		'',
		'Every token is read from the custom properties declared in a global scope in',
		'`src/lib/styles/*.css`.',
		'',
		'Every `--space-*` step is a class family: if `--space-md` exists, so do',
		'`.gap-md`, `.pad-md` and `.mar-md` (plus the `.px`/`.py`/`.pt` sides). There is',
		'no second vocabulary to learn.',
		'',
		'The names are the contract; the values are that version\'s defaults. A token',
		'declared on a component rather than `:root` is the component\'s own channel and',
		'is not listed here.'
	];

	const claimed = new Set<string>();
	for (const group of TOKEN_GROUPS) {
		const items = facts.tokens.filter((token) => !claimed.has(token.name) && group.match(token.name));
		for (const token of items) claimed.add(token.name);
		if (items.length === 0) continue;
		md.push('', `## ${group.title}`, '', group.blurb, '', '| Token | Value |', '|:---|:---|');
		for (const token of items) {
			md.push(`| \`${token.name}\` | \`${escapeCell(token.value)}\` |`);
		}
	}

	const rest = facts.tokens.filter((token) => !claimed.has(token.name));
	if (rest.length > 0) {
		md.push(
			'',
			'## Other Channels',
			'',
			'Written by a class or by JavaScript rather than themed per screen. Read them, do not invent neighbours.',
			'',
			'| Token | Value |',
			'|:---|:---|'
		);
		for (const token of rest) md.push(`| \`${token.name}\` | \`${escapeCell(token.value)}\` |`);
	}

	md.push('');
	return md.join('\n');
}

// -----------------------------------------------------------------------------
// Region injection
// -----------------------------------------------------------------------------

const REGION = /<!--\s*gen:begin\s+([\w.:-]+)\s*-->([\s\S]*?)<!--\s*gen:end\s+\1\s*-->/g;

function renderRegion(key: string, facts: Facts): string {
	if (key === 'cascade') return renderCascade(facts);
	if (key === 'counts') return renderCounts(facts);
	if (key.startsWith('css:')) return renderLayer(key.slice(4));
	if (key === 'classes') return facts.rows.length + ' rows — generated whole in references/classes-index.md';
	if (key === 'tokens') return facts.tokens.length + ' tokens — generated whole in references/tokens.md';
	throw new Error(`unknown region "${key}" — add it to renderRegion()`);
}

function inject(text: string, facts: Facts, warnings: string[]): string {
	// The markers are the source's business. The emitted skill reads as prose:
	// a reader there has nothing to fill, so the fences come off.
	return text.replace(REGION, (_whole, key: string) => renderRegion(key, facts));
}

/** An agent skill's frontmatter must stay the first bytes, so the banner follows it. */
function withBanner(text: string): string {
	if (text.startsWith('---')) {
		const end = text.indexOf('\n---', 3);
		if (end !== -1) {
			const after = text.indexOf('\n', end + 4);
			if (after !== -1) return `${text.slice(0, after + 1)}\n${BANNER}${text.slice(after + 1)}`;
		}
	}
	return `${BANNER}\n${text}`;
}

// -----------------------------------------------------------------------------
// Emit
// -----------------------------------------------------------------------------

function markdownFiles(dir: string, base = dir): string[] {
	const out: string[] = [];
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		// `scripts/` is bundled tooling, copied verbatim — never prose.
		if (entry.isDirectory() && path.relative(base, full) !== 'scripts') out.push(...markdownFiles(full, base));
		else if (entry.name.endsWith('.md')) out.push(path.relative(base, full));
	}
	return out.sort();
}

interface Emitted {
	path: string;
	content: string;
}

/** Build every file of the skill in memory. Nothing is written here. */
export function buildSkill(): { files: Emitted[]; warnings: string[] } {
	if (!fs.existsSync(SOURCE_DIR)) throw new Error(`no skill source at ${SOURCE_DIR}`);

	const { rows, tokens } = buildRegistry();
	const facts: Facts = { rows, tokens, files: styleFiles(), cascade: cascadeFiles() };
	const warnings: string[] = [];
	const files: Emitted[] = [];
	const generated = new Set(Object.keys(GENERATED_FILES));

	for (const relative of markdownFiles(SOURCE_DIR)) {
		if (generated.has(relative)) {
			warnings.push(`docs/fractalstyler-master/${relative} is generated whole — remove it from the source`);
			continue;
		}
		const source = fs.readFileSync(path.join(SOURCE_DIR, relative), 'utf8');
		const filled = inject(source, facts, warnings);
		// A marker without its closing partner renders as literal text; say so
		// rather than shipping prose an agent would read as instructions.
		for (const match of filled.matchAll(/<!--\s*gen:begin\s+([\w.:-]+)\s*-->/g)) {
			if (!filled.includes(`gen:end ${match[1]}`)) warnings.push(`${relative}: unclosed gen:begin ${match[1]}`);
		}
		files.push({ path: relative, content: withBanner(filled) });
	}

	for (const [relative, render] of Object.entries(GENERATED_FILES)) {
		files.push({ path: relative, content: `${BANNER}\n${render(facts)}` });
	}

	return { files, warnings };
}

/** Copy the bundled tooling (the untailwind script and its vendor) verbatim. */
function copyAssets(report: boolean): string[] {
	const assets = path.join(SOURCE_DIR, 'scripts');
	if (!fs.existsSync(assets)) return [];
	const placed: string[] = [];
	const walk = (dir: string): void => {
		for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
			const full = path.join(dir, entry.name);
			if (entry.isDirectory()) {
				walk(full);
				continue;
			}
			const relative = path.relative(SOURCE_DIR, full);
			placed.push(relative);
			if (report) continue;
			const target = path.join(OUT_DIR, relative);
			fs.mkdirSync(path.dirname(target), { recursive: true });
			fs.copyFileSync(full, target);
		}
	};
	walk(assets);
	return placed.sort();
}

function main(): void {
	const mode = process.argv.includes('--check')
		? 'check'
		: process.argv.includes('--report')
			? 'report'
			: 'write';
	const { files, warnings } = buildSkill();
	const assets = copyAssets(mode !== 'write');

	for (const warning of warnings) console.warn(`  ⚠ ${warning}`);

	const classCount = buildRegistry().rows.length;

	if (mode === 'report') {
		console.log(`✔ Skill would be written to ${path.relative(PKG_ROOT, OUT_DIR)}`);
		for (const file of files) console.log(`  ${file.path.padEnd(40)} ${file.content.split('\n').length} lines`);
		console.log(`  ${assets.length} bundled script files`);
		return;
	}

	if (mode === 'check') {
		const stale: string[] = [];
		for (const file of files) {
			const target = path.join(OUT_DIR, file.path);
			if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== file.content) stale.push(file.path);
		}
		if (stale.length > 0) {
			console.error(`✕ ${stale.length} stale skill file(s) — run npm run registry:`);
			for (const file of stale) console.error(`  ${file}`);
			process.exit(1);
		}
		console.log(`✔ Skill is current (${files.length} files, ${classCount} classes).`);
		return;
	}

	fs.rmSync(OUT_DIR, { recursive: true, force: true });
	for (const file of files) {
		const target = path.join(OUT_DIR, file.path);
		fs.mkdirSync(path.dirname(target), { recursive: true });
		fs.writeFileSync(target, file.content, 'utf8');
	}
	copyAssets(false);

	console.log(`✔ Skill written: ${files.length} files, ${classCount} classes, from docs/fractalstyler-master.`);
	console.log(`  Emit: skills/fractalstyler-master/ (SKILL.md, ${files.length - 1} reference files, ${assets.length} bundled script files)`);
}

if (process.argv[1] && /build-skill\.(ts|js|mjs)$/.test(process.argv[1])) main();
