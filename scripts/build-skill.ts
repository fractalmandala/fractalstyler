#!/usr/bin/env node
// =============================================================================
// build-skill — emit the agent skill from its source and the live stylesheets.
//
//   node scripts/build-skill.ts            → writes skills/fractalstyler-master
//   node scripts/build-skill.ts --report    → prints what it would write
//   node scripts/build-skill.ts --check     → fails if the emitted skill is stale
//
// The prose lives in docs/fractalstyler-master and is hand-written. The facts —
// which classes exist, what declares them, which layer each one lives in, the
// token ladders, the cascade order — are read from src/lib/styles on every run
// and injected into the regions marked in the source:
//
//   <!-- gen:begin cascade -->    … <!-- gen:end cascade -->
//   <!-- gen:begin css:containers.css --> … <!-- gen:end css:containers.css -->
//   <!-- gen:begin counts -->     … <!-- gen:end counts -->
//
// Everything outside a region is copied verbatim. Two files are generated
// whole because they are nothing but facts: references/classes-index.md and
// references/tokens.md.
//
// `npm run registry` runs update-registry.ts first, then this. The skill is
// generated, so never edit skills/fractalstyler-master by hand — edit the
// source in docs/fractalstyler-master.
// =============================================================================

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { styleFiles, cascadeFiles, FILE_INTROS, buildRegistry, CASCADE_ENTRY, type VocabEntry } from './update-registry.ts';
import type { Token } from './css.ts';

const PKG_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STYLES_DIR = path.join(PKG_ROOT, 'src', 'lib', 'styles');
const SOURCE_DIR = path.join(PKG_ROOT, 'docs', 'fractalstyler-master');
const OUT_DIR = path.join(PKG_ROOT, 'skills', 'fractalstyler-master');
const SCRIPT_PATH = 'scripts/build-skill.ts';

const BANNER = [
	'<!--',
	`\tGENERATED by ${SCRIPT_PATH} — do not edit this copy.`,
	'\tSource: docs/fractalstyler-master (prose) + src/lib/styles (facts).',
	'\tRegenerate: npm run registry',
	'-->',
	''
].join('\n');

/** A file that is nothing but facts, so it is written whole. */
const GENERATED_FILES: Record<string, (facts: Facts) => string> = {
	'references/classes-index.md': renderClassIndex,
	'references/tokens.md': renderTokenIndex
};

interface Facts {
	rows: VocabEntry[];
	tokens: Token[];
	/** Every layer, cascade first, then the detached and the unaccounted for. */
	files: string[];
	/** Only the layers index.css imports, in order — the cascade itself. */
	cascade: string[];
}

// -----------------------------------------------------------------------------
// Fact renderers — the regions the source marks, and the two generated files
// -----------------------------------------------------------------------------

/** The cascade, as one line of backticked layer names in the order they load. */
function renderCascade(facts: Facts): string {
	return facts.cascade.map((file) => `\`${file.replace(/\.css$/, '')}\``).join(' → ');
}

/** The layer count, the class count, the token count — the numbers prose quotes. */
function renderCounts(facts: Facts): string {
	return `${facts.rows.length} classes, ${facts.tokens.length} tokens, ${facts.files.length} layers`;
}

/** A stylesheet, verbatim, as a ```css fence. The definition layer is the truth. */
function renderLayer(file: string): string {
	const source = path.join(STYLES_DIR, file);
	if (!fs.existsSync(source)) throw new Error(`no such layer: ${file}`);
	const css = fs.readFileSync(source, 'utf8').trim();
	return ['```css', css, '```'].join('\n');
}

function escapeCell(text: string): string {
	return text.replace(/\|/g, '\\|');
}

/** Every class the system defines, grouped by the layer that declares it. */
function renderClassIndex(facts: Facts): string {
	const md: string[] = [
		'# Class Index',
		'',
		`**${facts.rows.length} classes** across **${facts.files.length} layers**, read from the`,
		'',
		'These classes are the entire public API. There is no authoring mixin and no',
		'styling function — `+stack`, `+surface`, `space()` and their friends do not',
		'exist. Compose in markup, and if a class is absent here it does not exist.',
		'',
		'Space families (`.gap` `.rgap` `.cgap` `.pad` `.px` `.py` `.pt` `.pr` `.pb` `.pl`',
		'`.mar` `.mx` `.my` `.mt` `.mr` `.mb` `.ml`) each run the eight steps',
		'`xs sm md bs lg xl 2xl 3xl`, token-routed through `var(--space-*)`. A modifier',
		'rides its base (`.row.xcenter`); a child carries its own name and names its',
		'parent (`.avatar-more` inside `.avatar-group`).',
		'',
		`Layers detached from \`${CASCADE_ENTRY}\` (\`custom.css\`, \`modular.css\`) still define`,
		'classes — they are opt-in, not imaginary.',
		''
	];

	for (const file of facts.files) {
		const items = facts.rows.filter((row) => row.file === file);
		if (items.length === 0) continue;
		md.push('---', '', `## ${file}`, '');
		if (FILE_INTROS[file]) md.push(FILE_INTROS[file], '');
		md.push('| Class | Kind | Parent | Applies |', '|:---|:---|:---|:---|');
		for (const item of items) {
			const applies = escapeCell(item.description || item.property || '—');
			const parent = item.parent ? `\`${item.parent}\`` : '—';
			md.push(`| \`${item.class}\` | ${item.kind} | ${parent} | ${applies} |`);
		}
		md.push('');
	}

	return md.join('\n');
}

